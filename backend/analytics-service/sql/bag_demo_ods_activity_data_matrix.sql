-- Activity x TRB matrix store, parallel to ods.churn_data_matrix (which is
-- Churn x TRB). Structure-only (no data). Same shape as churn_data_matrix with
-- churn_category replaced by activity_category.
--
-- Run against database: bag_demo

CREATE SCHEMA IF NOT EXISTS ods;

CREATE TABLE IF NOT EXISTS ods.activity_data_matrix (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cif                   varchar(50)  NOT NULL,
    activity_category     varchar(10),               -- activity tier/segment (was churn_category in churn matrix)
    trb_category          varchar(10),
    matrix_classification varchar(10),
    created_ts            timestamptz  NOT NULL DEFAULT now(),
    updated_ts            timestamptz  NOT NULL DEFAULT now(),
    is_selected           boolean      NOT NULL DEFAULT false
);

-- Unique CIF (one matrix row per customer).
CREATE UNIQUE INDEX IF NOT EXISTS uidx_ods_activity_data_matrix_cif
    ON ods.activity_data_matrix (cif);

-- Category lookup (activity_category, trb_category).
CREATE INDEX IF NOT EXISTS idx_ods_activity_data_matrix_cat
    ON ods.activity_data_matrix (activity_category, trb_category);

-- Matrix classification lookup.
CREATE INDEX IF NOT EXISTS idx_ods_activity_data_matrix_mx
    ON ods.activity_data_matrix (matrix_classification);

-- Selection flag lookup (used by the Hot Target / Detail Action Plan queries).
CREATE INDEX IF NOT EXISTS idx_ods_activity_data_matrix_selected
    ON ods.activity_data_matrix (is_selected);
