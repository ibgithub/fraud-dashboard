-- Structure-only clone of altair_demo.churn.churn_data_matrix into
-- bag_demo.ods.churn_data_matrix, with aum_category renamed to trb_category.
-- The source churn schema/table does not exist in bag_demo yet; this creates
-- just the structure (no data) so the Customer Matrix selection can be
-- persisted here later.
--
-- Run against database: bag_demo

CREATE SCHEMA IF NOT EXISTS ods;

CREATE TABLE IF NOT EXISTS ods.churn_data_matrix (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cif                   varchar(50)  NOT NULL,
    churn_category        varchar(10),
    trb_category          varchar(10),               -- was aum_category in altair_demo
    matrix_classification varchar(10),
    created_ts            timestamptz  NOT NULL DEFAULT now(),
    updated_ts            timestamptz  NOT NULL DEFAULT now(),
    is_selected           boolean      NOT NULL DEFAULT false
);

-- Unique CIF (one matrix row per customer).
CREATE UNIQUE INDEX IF NOT EXISTS uidx_ods_churn_data_matrix_cif
    ON ods.churn_data_matrix (cif);

-- Category lookup (churn_category, trb_category).
CREATE INDEX IF NOT EXISTS idx_ods_churn_data_matrix_cat
    ON ods.churn_data_matrix (churn_category, trb_category);

-- Matrix classification lookup.
CREATE INDEX IF NOT EXISTS idx_ods_churn_data_matrix_mx
    ON ods.churn_data_matrix (matrix_classification);

-- Selection flag lookup (used by the Hot Target / Detail Action Plan queries).
CREATE INDEX IF NOT EXISTS idx_ods_churn_data_matrix_selected
    ON ods.churn_data_matrix (is_selected);
